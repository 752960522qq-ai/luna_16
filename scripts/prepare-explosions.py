"""Build mobile flipbooks from the three user-supplied TGA ZIPs.

Usage: python scripts/prepare-explosions.py /path/to/upload
48 frames, one padded 1568x1176 WebP per effect; source archives stay untouched.
"""
import hashlib
import io
import json
import sys
import zipfile
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'app/src/main/assets/effects'
OUT.mkdir(parents=True, exist_ok=True)
definitions = [('small', 'Explosion01-nofire', 1.4, 8),
               ('medium', 'Explosion02', 1.9, 18),
               ('large', 'FireBall02', 2.6, 32)]
metadata = {}
for name, prefix, duration, diameter in definitions:
    archive = next(Path(sys.argv[1]).glob(prefix + '*sequence*.zip'))
    with zipfile.ZipFile(archive) as z:
        files = sorted(n for n in z.namelist() if n.lower().endswith('.tga'))
        # Dense sampling of the ignition, followed by the expansion/tail.
        indices = sorted(set([1, 2, 3, 4] + [round(5 + i * (len(files)-6)/43) for i in range(44)]))
        tile, padding, columns, rows = 196, 2, 8, 6
        atlas = Image.new('RGBA', (tile * columns, tile * rows))
        additive = Image.open(io.BytesIO(z.read(files[0]))).mode == 'RGB'
        for frame, source_index in enumerate(indices):
            image = Image.open(io.BytesIO(z.read(files[source_index]))).convert('RGBA')
            image = image.resize((192, 192), Image.Resampling.LANCZOS)
            x, y = frame % columns * tile + padding, frame // columns * tile + padding
            atlas.paste(image, (x, y))
            # Extruded gutters avoid neighbouring-frame bleeding on linear filtering.
            atlas.paste(image.crop((0, 0, 1, 192)).resize((padding, 192)), (x-padding, y))
            atlas.paste(image.crop((191, 0, 192, 192)).resize((padding, 192)), (x+192, y))
            atlas.paste(image.crop((0, 0, 192, 1)).resize((192, padding)), (x, y-padding))
            atlas.paste(image.crop((0, 191, 192, 192)).resize((192, padding)), (x, y+192))
        path = OUT / (name + '.webp')
        atlas.save(path, 'WEBP', quality=85, method=6, exact=True)
        metadata[name] = dict(path='effects/'+path.name, frames=len(indices), columns=columns,
            rows=rows, tile=tile, padding=padding, content=192, duration=duration, diameter=diameter,
            additive=additive, sourceArchive=archive.name, sourceFrames=len(files), sourceIndices=indices,
            sourceSha256=hashlib.sha256(archive.read_bytes()).hexdigest(),
            sha256=hashlib.sha256(path.read_bytes()).hexdigest())
        print(name, len(indices), path.stat().st_size, 'bytes', 'additive' if additive else 'alpha')
(OUT / 'sequences.js').write_text('// Generated by scripts/prepare-explosions.py; user-provided assets.\n'
    + 'export const EXPLOSION_SEQUENCES = ' + json.dumps(metadata, indent=2) + ';\n')
