const assert=require('node:assert/strict');
const B=require('../app/src/main/assets/engine.js');
const {Progress,KEY}=require('../app/src/main/assets/progress.js');
const ranks={gladiator_kfz:1,warhorse:2,annihilator_fv:2,handlv_missile:1,b_tank:1,kfz_artillery:2,hero_tank:3,cougar_artillery:4,black_turtle:6,longnose_artillery:6};
const hp={gladiator_kfz:95,warhorse:210,annihilator_fv:125,handlv_missile:100,b_tank:170,kfz_artillery:110,hero_tank:285,cougar_artillery:165,black_turtle:165,longnose_artillery:255};
const physical={gladiator_kfz:[35,6,'medium'],warhorse:[40,7,'medium'],annihilator_fv:[64,8,'medium'],handlv_missile:[113,10,'good'],b_tank:[44,9,'medium'],kfz_artillery:[42,10,'medium'],hero_tank:[40,15,'poor'],cougar_artillery:[48,10,'medium'],black_turtle:[62,10,'medium'],longnose_artillery:[60,4,'good']};
for(const [id,v] of Object.entries(B.VEHICLES)){
 assert.equal(v.tier,ranks[id],id+' tier');assert.equal(v.hp,hp[id],id+' durability');
 assert.equal(v.speed,physical[id][0]/3.6,id+' historical forward speed');
 assert.equal(v.reverseSpeed,physical[id][1]/3.6,id+' historical reverse speed');
 assert.equal(v.turnRating,physical[id][2],id+' historical turning profile');
 assert.ok(B.matchCandidates(id).every(k=>Math.abs(v.tier-B.VEHICLES[k].tier)<=1),id+' matchmaking');
}
assert.equal(B.VEHICLES.black_turtle.launcherYaw,85*Math.PI/180);
assert.equal(B.VEHICLES.cougar_artillery.turretYaw,30*Math.PI/180);
assert.equal(B.VEHICLES.cougar_artillery.mass,44);
assert.equal(B.weaponSpec({vehicleId:'hero_tank'},'tankCannon').cooldown,10);
assert.equal(B.weaponSpec({vehicleId:'cougar_artillery'},'artillery').cooldown,30);
assert.equal(B.weaponSpec({vehicleId:'black_turtle'},'missile').speed,155*1.05);
assert.equal(B.weaponSpec({vehicleId:'black_turtle'},'uav').recon,460);
assert.equal(B.weaponSpec({vehicleId:'longnose_artillery'},'mg').groundDamage,2);
assert.equal(B.weaponSpec({vehicleId:'longnose_artillery'},'artillery').blastRadius,26);
assert.equal(B.weaponSpec({vehicleId:'black_turtle'},'missile').blastRadius,12);
const battle=(a,b)=>new B.Engine({mode:'lan',countdown:0,vehicles:[a,b]});
let e=battle('handlv_missile','b_tank');
e.damage(e.players[1],0,80,'missile');assert.equal(e.players[1].hp,82,'missile vs tank');
e=battle('b_tank','kfz_artillery');e.damage(e.players[1],0,50,'autocannon');assert.equal(e.players[1].hp,55,'tank vs artillery');
e=battle('longnose_artillery','black_turtle');e.damage(e.players[1],0,100,'artillery');assert.equal(e.players[1].hp,55,'artillery vs missile');
e=battle('handlv_missile','kfz_artillery');e.damage(e.players[1],0,80,'missile');assert.equal(e.players[1].hp,30,'no boost vs other target');
e=battle('longnose_artillery','black_turtle');e.damage(e.players[1],0,30,'uav');assert.equal(e.players[1].hp,135,'no boost for UAV');
e=battle('hero_tank','longnose_artillery');e.players[0].heArmed=true;
const shot=e.launch(e.players[0],'tankCannon');
assert.equal(shot.blastSpec.directDamage,135);assert.equal(shot.blastSpec.blastRadius,15);
assert.equal(e.players[0].heArmed,false);
const data=new Map(),storage={getItem:k=>data.get(k)||null,setItem:(k,v)=>data.set(k,v)};
data.set(KEY,JSON.stringify({version:2,coins:1234,owned:['handlv_missile','black_turtle','longnose_artillery'],researched:['black_turtle','longnose_artillery'],selected:'black_turtle'}));
const p=new Progress(storage);assert.ok(p.owned.includes('black_turtle'));assert.ok(p.owned.includes('longnose_artillery'));assert.equal(p.selected,'black_turtle');
assert.equal(p.reward('eight-tier','win',{vehicleId:'black_turtle',roomTier:8}),450);assert.equal(p.lastResearch,180);
console.log('PASS eight-tier roster, physical speed/turning, class counters, HE, save migration, rewards');
